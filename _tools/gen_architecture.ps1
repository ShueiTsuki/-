$noDoc = New-Object System.Collections.Generic.List[string]
$totalFiles = 0

foreach ($layer in $layers.Keys) {
    $dir = Join-Path $mod $layer
    if (-not (Test-Path $dir)) { continue }
    [void]$sb.AppendLine("### $layer/")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('| 文件 | 职责 |')
    [void]$sb.AppendLine('|---|---|')
    $files = Get-ChildItem $dir -Recurse -File -Filter *.cs |
             Where-Object { $_.FullName -notmatch '\\(obj|bin)\\' } | Sort-Object FullName
    foreach ($f in $files) {
        $totalFiles++
        $rel = $f.FullName.Replace("$dir\", '').Replace('\', '/')
        $resp = Get-Responsibility $f.FullName
        if ($resp -eq '') {
            $noDoc.Add("$layer/$rel")
            $resp = '**（无文件头说明）**'
        }
        [void]$sb.AppendLine("| ``$rel`` | $resp |")
    }
    [void]$sb.AppendLine()
}

