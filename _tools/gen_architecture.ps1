# 从文件头注释里抽"一句话职责"：
#   优先取 XML 文档注释 `<summary>` 之后的第一行非空 `///`；
#   没有就取第一个 `//` 注释行；都没有就标记出来（这也是文档覆盖率指标）。
function Get-Responsibility($path) {
    $lines = Get-Content -LiteralPath $path -TotalCount 60
    $inSummary = $false
    foreach ($l in $lines) {
        $t = $l.Trim()
        if ($t -match '^///\s*<summary>') {
            $rest = ($t -replace '^///\s*<summary>', '').Trim()
            if ($rest -ne '' -and $rest -notmatch '^</summary>') { return $rest }
            $inSummary = $true
            continue
        }
        if ($inSummary) {
            if ($t -match '^///\s*</summary>') { break }
            $body = ($t -replace '^///', '').Trim()
            if ($body -ne '') { return $body }
        }
    }
    foreach ($l in $lines) {
        $t = $l.Trim()
        if ($t -match '^//\s*(.+)$') {
            $body = $Matches[1].Trim()
            if ($body -ne '' -and $body -notmatch '^<auto-generated') { return $body }
        }
    }
    return ''
}

